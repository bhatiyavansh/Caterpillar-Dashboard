def _operator_stats() -> pd.DataFrame:
    daily = _daily()
    if daily.empty:
        return pd.DataFrame()
    stats = daily.groupby("operator_id", as_index=False).agg(
        fuel_l=("fuel_l", "sum"), cycles=("cycles", "sum"),
        idle_min=("idle_min", "sum"), belt_off_min=("belt_off_min", "sum"),
        minutes=("minutes", "sum"), working_min=("working_min", "sum"),
    )
    stats["idle_ratio"] = stats["idle_min"] / stats["minutes"]
    stats["belt_off_ratio"] = stats["belt_off_min"] / stats["minutes"]
    stats["hours"] = stats["minutes"] / 60.0
    stats["cycles_per_hour"] = stats["cycles"] / stats["hours"].clip(lower=1e-6)

    incidents = _incidents()
    counts = {}
    if not incidents.empty:
        for op, rows in incidents.groupby("operator_id"):
            counts[op] = {
                "near_miss": int(rows["type"].isin(["proximity", "v2v"]).sum()),
                "tip_over": int((rows["type"] == "tip_over").sum()),
            }
    stats["near_misses"] = stats["operator_id"].map(
        lambda o: counts.get(o, {}).get("near_miss", 0)
    )
    stats["tip_overs"] = stats["operator_id"].map(
        lambda o: counts.get(o, {}).get("tip_over", 0)
    )

    # A truck driver's loads per hour and an excavator operator's cycles per
    # hour are different units.  Efficiency is therefore scored against the
    # median for the *same machine type*, or everyone on a high-cycle machine
    # pins at 100 and the leaderboard says nothing.
    machines = _machines()
    type_by_machine = (
        dict(zip(machines["machine_id"], machines["machine_type"]))
        if not machines.empty else {}
    )
    daily_machine = daily.groupby("operator_id")["machine_id"].first()
    stats["machine_type"] = stats["operator_id"].map(
        lambda o: type_by_machine.get(daily_machine.get(o, ""), "excavator")
    )
    stats["peer_median_cph"] = stats.groupby("machine_type")["cycles_per_hour"].transform(
        "median"
    ).clip(lower=1e-6)
    return stats


def leaderboard() -> list[dict]:
    """Safety and efficiency scores per operator, ranked."""
    stats = _operator_stats()
    operators = _operators()
    if stats.empty:
        return []

    names = dict(zip(operators["operator_id"], operators["name"])) if not operators.empty else {}

    rows = []
    for _, s in stats.iterrows():
        per_100h = 100.0 / max(s["hours"], 1e-6)
        safety = _clamp(
            100
            - 30 * s["belt_off_ratio"]
            - 5 * (s["near_misses"] * per_100h)
            - 3 * (s["tip_overs"] * per_100h)
        )
        efficiency = _clamp(
            50 * (s["cycles_per_hour"] / s["peer_median_cph"]) + 50 * (1 - s["idle_ratio"])
        )
        rows.append({
            "operator_id": s["operator_id"],
            "name": names.get(s["operator_id"], s["operator_id"]),
            "safety_score": round(safety),
            "efficiency_score": round(efficiency),
            "seatbelt_compliance_pct": round((1 - s["belt_off_ratio"]) * 100, 1),
            "idle_pct": round(s["idle_ratio"] * 100, 1),
            "cycles_per_hour": round(s["cycles_per_hour"], 1),
            "machine_type": s["machine_type"],
            "near_misses": int(s["near_misses"]),
            "hours": round(s["hours"], 1),
        })

    rows.sort(key=lambda r: (r["safety_score"] + r["efficiency_score"]), reverse=True)
    for i, r in enumerate(rows, start=1):
        r["rank"] = i
        r["trend"] = "up" if i <= len(rows) / 3 else ("down" if i > 2 * len(rows) / 3 else "flat")
    return rows


def training_profiles() -> list[dict]:
    """Skill levels per operator, plus what to train next."""
    board = {r["operator_id"]: r for r in leaderboard()}
    operators = _operators()
    if operators.empty:
        return []

    out = []
    for _, op in operators.iterrows():
        row = board.get(op["operator_id"])
        base = {"novice": 45, "intermediate": 68, "expert": 86}[op["skill"]]
        safety = row["safety_score"] if row else base
        efficiency = row["efficiency_score"] if row else base

        skills = {
            "digging": _clamp(base + (efficiency - 70) * 0.35),
            "swinging": _clamp(base + (efficiency - 70) * 0.25 - 3),
            "slope_work": _clamp(base - 6 + (safety - 80) * 0.3),
            "safety": _clamp(safety),
            "fuel_efficiency": _clamp(
                base + (100 - (row["idle_pct"] if row else 25)) * 0.15 - 8
            ),
        }
        skills = {k: round(v) for k, v in skills.items()}
        weakest = min(skills, key=skills.get)
        completed = max(0, int((base - 40) / 12))

        out.append({
            "operator_id": op["operator_id"],
            "name": op["name"],
            "skill": op["skill"],
            "years_experience": float(op["years_experience"]),
            "skills": skills,
            "overall": round(float(np.mean(list(skills.values())))),
            "completed_modules": list(MODULES[:completed]),
            "recommended_next_module": {
                "digging": "Trenching technique",
                "swinging": "Load handling",
                "slope_work": "Slope and bench safety",
                "safety": "Working near ground crew",
                "fuel_efficiency": "Fuel-efficient operation",
            }[weakest],
            "weakest_skill": weakest,
        })
    out.sort(key=lambda r: r["overall"], reverse=True)
    return out


