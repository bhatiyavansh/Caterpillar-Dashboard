def fleet_kpis(world_snapshot: dict | None = None) -> dict:
    """Top-of-screen numbers for the site manager.

    Uses the live simulator snapshot when one is passed, and falls back to the
    most recent day of history so the screen is never blank.
    """
    daily = _daily()
    machines = _machines()
    total_machines = int(len(machines)) if not machines.empty else 10

    if daily.empty:
        today = pd.DataFrame()
    else:
        today = daily[daily["date"] == daily["date"].max()]

    fuel_today = float(today["fuel_l"].sum()) if len(today) else 0.0
    idle_cost = float(today["idle_cost_inr"].sum()) if len(today) else 0.0
    utilization = float(today["utilization_pct"].mean()) if len(today) else 0.0

    incidents = _incidents()
    near_misses = 0
    alerts = 0
    critical = 0
    if not incidents.empty:
        latest_day = incidents["date"].max()
        day_rows = incidents[incidents["date"] == latest_day]
        alerts = int(len(day_rows))
        critical = int((day_rows["severity"] == "critical").sum())
        near_misses = int(day_rows["type"].isin(["proximity", "v2v"]).sum())

    active = total_machines - 1
    risk = {"score": 42, "level": "medium"}

    if world_snapshot:
        states = world_snapshot.get("machines", [])
        if states:
            active = sum(1 for s in states if s.get("engine_on"))
            fuel_today = round(sum(float(s.get("fuel_used_l", 0)) for s in states), 1)
            idle_cost = round(sum(
                _idle_cost(s["machine_id"], float(s.get("idle_min", 0))) for s in states
            ))
            working = sum(1 for s in states if s.get("status") == "working")
            engine_on = max(sum(1 for s in states if s.get("engine_on")), 1)
            utilization = round(working / engine_on * 100, 1)
        env = world_snapshot.get("environment", {})
        events = world_snapshot.get("recent_events", [])
        if events:
            alerts = len(events)
            critical = sum(1 for e in events if e.get("severity") == "critical")
            near_misses = sum(
                1 for e in events
                if e.get("event") in ("proximity_alert", "v2v_collision_risk")
            )
        from .risk import get_working_risk
        risk = get_working_risk(
            weather=env.get("weather", "clear"),
            temperature_c=env.get("temperature_c", 33.0),
            visibility_m=env.get("visibility_m", 10_000.0),
            ground=env.get("ground", "dry"),
            hours_on_shift=env.get("hours_on_shift", 0.0),
        )
        risk = {"score": risk["score"], "level": risk["level"]}

    return {
        "ts": _iso(),
        "active_machines": int(active),
        "total_machines": total_machines,
        "alerts_today": int(alerts),
        "critical_alerts_today": int(critical),
        "utilization_pct": round(utilization),
        "fuel_today_l": round(fuel_today, 1),
        "idle_cost_today_inr": int(idle_cost),
        "near_misses_today": int(near_misses),
        "working_risk": risk,
    }


