"""Screen summaries.

D's screens show many numbers that are not in the live stream - costs, carbon,
utilisation, leaderboards, skill profiles.  These functions compute them from
`data/` plus, where available, the simulator's current state.

Every function returns exactly the shape of its fixture in `fixtures/`, because
the fixtures are generated by calling these functions.  They cannot drift.

Score formulas are deliberately simple and explainable:
  safety     = 100 - 30*(belt-off ratio) - 5*(near-misses/100h) - 3*(tip-overs/100h)
  efficiency = 50*(cycles per hour / fleet median) + 50*(1 - idle ratio)
  utilisation = working minutes / engine-on minutes
"""

from __future__ import annotations

from datetime import datetime, timedelta, timezone
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

from simulator.config import CO2_KG_PER_LITRE, DIESEL_PRICE_INR, SPECS

DATA = Path(__file__).resolve().parent.parent / "data"

SKILLS = ("digging", "swinging", "slope_work", "safety", "fuel_efficiency")
MODULES = (
    "Pre-start inspection", "Trenching technique", "Slope and bench safety",
    "Fuel-efficient operation", "Working near ground crew", "Load handling",
)


def _iso(ts=None) -> str:
    ts = ts or datetime.now(timezone.utc)
    return pd.Timestamp(ts).strftime("%Y-%m-%dT%H:%M:%SZ")


def _clamp(v: float, lo: float = 0.0, hi: float = 100.0) -> float:
    return float(min(max(v, lo), hi))


@lru_cache(maxsize=1)
def _telemetry() -> pd.DataFrame:
    path = DATA / "telemetry.csv"
    if not path.exists():
        return pd.DataFrame()
    df = pd.read_csv(path, parse_dates=["timestamp"])
    df = df[df["task_id"] != "BRIEF"]           # the brief's rows are from 2025
    df["date"] = df["timestamp"].dt.date
    df["belt_off"] = df["seatbelt"].astype(str).str.lower() == "unfastened"
    df["working"] = df["idle_min"] <= 0
    return df


@lru_cache(maxsize=1)
def _machines() -> pd.DataFrame:
    path = DATA / "machines.csv"
    return pd.read_csv(path) if path.exists() else pd.DataFrame()


@lru_cache(maxsize=1)
def _operators() -> pd.DataFrame:
    path = DATA / "operators.csv"
    return pd.read_csv(path) if path.exists() else pd.DataFrame()


@lru_cache(maxsize=1)
def _incidents() -> pd.DataFrame:
    path = DATA / "incidents.csv"
    if not path.exists():
        return pd.DataFrame()
    df = pd.read_csv(path, parse_dates=["timestamp"])
    df["date"] = df["timestamp"].dt.date
    return df


def clear_cache() -> None:
    """Call after regenerating `data/`."""
    for fn in (_telemetry, _machines, _operators, _incidents):
        fn.cache_clear()


# --------------------------------------------------------------------------
# per-day aggregates, the basis for most of the screens
# --------------------------------------------------------------------------

def _daily() -> pd.DataFrame:
    t = _telemetry()
    if t.empty:
        return pd.DataFrame()
    g = t.groupby(["date", "machine_id", "operator_id"], as_index=False).agg(
        fuel_l=("fuel_used_l", "sum"),
        cycles=("load_cycles", "sum"),
        idle_min=("idle_min", "sum"),
        belt_off_min=("belt_off", "sum"),
        minutes=("timestamp", "count"),
        mean_hyd=("hydraulic_temp_c", "mean"),
    )
    g["working_min"] = g["minutes"] - g["idle_min"]
    g["utilization_pct"] = (g["working_min"] / g["minutes"] * 100).round(1)
    g["idle_pct"] = (g["idle_min"] / g["minutes"] * 100).round(1)
    g["idle_cost_inr"] = g.apply(
        lambda r: _idle_cost(r["machine_id"], r["idle_min"]), axis=1
    ).round(0)
    return g


def _idle_cost(machine_id: str, idle_min: float) -> float:
    machines = _machines()
    model = "320"
    if not machines.empty:
        row = machines[machines["machine_id"] == machine_id]
        if len(row):
            model = str(row.iloc[0]["model"])
    spec = SPECS.get(model)
    rate = spec.idle_fuel_lph if spec else 4.0
    return idle_min / 60.0 * rate * DIESEL_PRICE_INR


