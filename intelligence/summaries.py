def incident_index() -> list[dict]:
    """Incident list; `has_replay` marks the few with full 60-second tracks."""
    incidents = _incidents()
    if incidents.empty:
        return []
    track_dir = DATA / "incident_tracks"
    have = {p.stem for p in track_dir.glob("*.json")} if track_dir.exists() else set()

    out = []
    for _, r in incidents.iterrows():
        out.append({
            "incident_id": r["incident_id"],
            "ts": pd.Timestamp(r["timestamp"]).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "machine_id": r["machine_id"],
            "operator_id": r["operator_id"],
            "type": r["type"],
            "severity": r["severity"],
            "zone": r["zone"],
            "x": float(r["x"]),
            "y": float(r["y"]),
            "weather": r["weather"],
            "description": r["description"],
            "has_replay": r["incident_id"] in have,
        })
    out.sort(key=lambda r: r["ts"], reverse=True)
    return out


def heatmap_points(kind: str = "near_miss") -> list[dict]:
    """Points for A's heatmap layer: [{x, y, weight}]."""
    if kind == "near_miss":
        incidents = _incidents()
        if incidents.empty:
            return []
        rows = incidents[incidents["type"].isin(["proximity", "v2v"])]
        weight = {"critical": 1.0, "high": 0.75, "medium": 0.5, "low": 0.25}
        return [
            {"x": round(float(r["x"]), 1), "y": round(float(r["y"]), 1),
             "weight": weight.get(r["severity"], 0.5)}
            for _, r in rows.iterrows()
        ]

    if kind == "idle":
        # idle is not positional in the historical data, so attribute each
        # machine's idle minutes to the zone it works in
        from simulator.config import FLEET
        from simulator.site import zone_by_id

        daily = _daily()
        if daily.empty:
            return []
        totals = daily.groupby("machine_id")["idle_min"].sum()
        peak = float(totals.max()) or 1.0
        points = []
        rng = np.random.default_rng(42)
        for entry in FLEET:
            idle = float(totals.get(entry.machine_id, 0.0))
            if idle <= 0:
                continue
            zone = zone_by_id(entry.home_zone if entry.home_zone != "road" else "A")
            cx, cy = zone.centre
            for _ in range(8):
                points.append({
                    "x": round(float(cx + rng.normal(0, 18)), 1),
                    "y": round(float(cy + rng.normal(0, 18)), 1),
                    "weight": round(idle / peak, 2),
                })
        return points

    raise ValueError(f"unknown heatmap kind {kind!r}")
