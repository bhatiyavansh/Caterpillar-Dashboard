def utilization_series(days: int = 30) -> list[dict]:
    """Per-day utilisation, fuel and idle, fleet-wide and per machine."""
    daily = _daily()
    if daily.empty:
        return []
    dates = sorted(daily["date"].unique())[-days:]
    out = []
    for d in dates:
        rows = daily[daily["date"] == d]
        out.append({
            "date": str(d),
            "utilization_pct": round(float(rows["utilization_pct"].mean()), 1),
            "fuel_l": round(float(rows["fuel_l"].sum()), 1),
            "idle_pct": round(float(rows["idle_pct"].mean()), 1),
            "idle_cost_inr": int(rows["idle_cost_inr"].sum()),
            "cycles": int(rows["cycles"].sum()),
            "per_machine": [
                {
                    "machine_id": r["machine_id"],
                    "utilization_pct": round(float(r["utilization_pct"]), 1),
                    "fuel_l": round(float(r["fuel_l"]), 1),
                    "idle_pct": round(float(r["idle_pct"]), 1),
                }
                for _, r in rows.iterrows()
            ],
        })
    return out


def owner_summary(days: int = 7) -> dict:
    """Cost, carbon and utilisation for the machine owner."""
    series = utilization_series(days)
    if not series:
        return {
            "ts": _iso(), "days": days, "fuel_spend_inr": 0, "idle_cost_inr": 0,
            "co2_kg": 0, "utilization_pct": 0, "daily": [], "top_anomalies": [],
        }
    fuel_l = sum(d["fuel_l"] for d in series)
    idle_cost = sum(d["idle_cost_inr"] for d in series)

    try:
        from .anomaly import get_anomalies
        top = get_anomalies(since_hours=days * 24)[:3]
    except Exception:
        top = []

    return {
        "ts": _iso(),
        "days": days,
        "fuel_l": round(fuel_l, 1),
        "fuel_spend_inr": int(fuel_l * DIESEL_PRICE_INR),
        "idle_cost_inr": int(idle_cost),
        "idle_cost_share_pct": round(
            idle_cost / max(fuel_l * DIESEL_PRICE_INR, 1) * 100, 1
        ),
        "co2_kg": round(fuel_l * CO2_KG_PER_LITRE, 1),
        "utilization_pct": round(
            float(np.mean([d["utilization_pct"] for d in series])), 1
        ),
        "cycles": sum(d["cycles"] for d in series),
        "daily": series,
        "top_anomalies": top,
    }


